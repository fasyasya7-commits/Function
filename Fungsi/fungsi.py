# Mendefiniskan fungsi menghitung luas persegi panjang
def hitung_luas_persegi_panjang(panjang, lebar):
    return panjang * lebar

# Program Utama 
# Memanggil fungsi dan menampung hasilnya ke variabel 'hasil_luas'
hasil_luas = hitung_luas_persegi_panjang(5, 5)
print("Luas persegi panjang adalah:", hasil_luas)